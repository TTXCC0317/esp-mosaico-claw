"""Prune a generated ``<stem>_i18n.h`` against the binds gspc really compiled.

Authoring marks every translatable static label, but a label can be lowered
into a row template or otherwise dropped, so its ``GSP_BIND_`` constant never
reaches ``<stem>_binds.h``.  Referencing such a constant would break the App
registry translation unit, so keep only the binds that exist.

Usage: filter_i18n_header.py <generated_dir> <gsp_stem>
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ENTRY_RE = re.compile(r'^\s*\{ GSP_BIND_([0-9A-Za-z_]+), (.*) \},$', re.MULTILINE)
DEFINE_RE = re.compile(r'#define\s+GSP_BIND_([0-9A-Za-z_]+)')


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: filter_i18n_header.py <generated_dir> <gsp_stem>",
              file=sys.stderr)
        return 2
    out_dir = Path(sys.argv[1])
    stem = sys.argv[2]
    header = out_dir / f"{stem}_i18n.h"
    if not header.exists():
        return 0

    text = header.read_text(encoding="utf-8")
    if f"{stem}_i18n[1]" in text:
        return 0

    defined: set[str] = set()
    for path in out_dir.glob("*.h"):
        if path.name == header.name:
            continue
        defined |= set(DEFINE_RE.findall(
            path.read_text(encoding="utf-8", errors="ignore")))

    kept = [(name, value) for name, value in ENTRY_RE.findall(text)
            if name in defined]

    sym = re.sub(r"[^0-9A-Za-z_]", "_", stem)
    lines = [
        "/* Generated by scene_common. Do not edit. */",
        "#pragma once",
        "",
        '#include "mosaic_i18n.h"',
        "",
    ]
    if kept:
        lines.append(f'#include "{stem}_binds.h"')
        lines.append("")
        lines.append(f"static const mosaic_i18n_entry_t {sym}_i18n[] = {{")
        lines.extend(f"    {{ GSP_BIND_{name}, {value} }}," for name, value in kept)
        lines.append("};")
        lines.append(f"#define {sym}_i18n_count "
                     f"(sizeof({sym}_i18n) / sizeof({sym}_i18n[0]))")
    else:
        lines.append(f"static const mosaic_i18n_entry_t {sym}_i18n[1] = "
                     "{{0u, 0}};")
        lines.append(f"#define {sym}_i18n_count 0u")
    lines.append("")
    header.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())